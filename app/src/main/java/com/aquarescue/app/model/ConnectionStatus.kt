package com.aquarescue.app.model

enum class ConnectionStatus {
    /** Подключение выключено пользователем. */
    DISABLED,
    /** Первая попытка подключения. */
    CONNECTING,
    /** Данные поступают. */
    CONNECTED,
    /** Был сбой запроса, идут повторные попытки (данные ещё свежие). */
    RECONNECTING,
    /** Данных нет дольше порога — соединение потеряно, идут повторные попытки. */
    LOST,
}
